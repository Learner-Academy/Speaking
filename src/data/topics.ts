/**
 * Deterministic PRNG seeded formula to ensure 100% unique everyday sentences
 * across the entire 90-day program. If an exam is failed (<80%), weekSeed is
 * incremented, re-shuffling the week's sentences without altering other weeks.
 * Dynamically tailored for the learner's specific Age Group and Level.
 */
export function generateDailySentences(
  topicId: string,
  dayNumber: number,
  sentenceIdx: number,
  level: LearnerLevel,
  ageGroup: AgeGroup,
  weekSeed = 0
): DialoguePhrase {
  const weekNumber = Math.ceil(dayNumber / 7);
  // Calculate unique indices based on day, sentenceIdx, weekSeed
  const topicHash = topicId.split('').reduce((acc, c) => acc + c.charCodeAt(0), 0);
  const seedMultiplier = dayNumber * 73 + sentenceIdx * 19 + weekSeed * 31 + topicHash * 11;

  const openKey = (seedMultiplier + 1) % 5;
  const needKey = (seedMultiplier + 2) % 12;
  const markKey = (seedMultiplier + 3) % 3;

  const open = OPENING_CHUNKS[openKey];
  const need = TOPIC_OBJECT_NEEDS[needKey];
  const mark = POLITE_MARKERS[markKey];

  const targetPhrases: Record<LanguageCode, string> = {} as Record<LanguageCode, string>;
  const phonetics: Record<LanguageCode, string> = {} as Record<LanguageCode, string>;
  const translations: Record<LanguageCode, string> = {} as Record<LanguageCode, string>;

  const langCodes: LanguageCode[] = [
    'en', 'es', 'ur', 'hi', 'ar', 'fr', 'zh', 'de', 'pt', 'ru', 'ja', 'ko'
  ];

  for (const lang of langCodes) {
    if (ageGroup === '4-6') {
      // Age 4-6: Shorter, single child-friendly phrase
      if (level === 'Beginner') {
        if (lang === 'ja' || lang === 'ko') {
          targetPhrases[lang] = `${need.text[lang]}！`;
          phonetics[lang] = `${need.phonetics[lang]}!`;
        } else {
          targetPhrases[lang] = `${need.text[lang]}!`;
          phonetics[lang] = `${need.phonetics[lang]}!`;
        }
      } else {
        // Intermediate/Advanced for 4-6: single polite request
        if (lang === 'ja' || lang === 'ko') {
          targetPhrases[lang] = `${need.text[lang]} ${open.text[lang]}？`;
          phonetics[lang] = `${need.phonetics[lang]} ${open.phonetics[lang]}?`;
        } else {
          targetPhrases[lang] = `${open.text[lang]} ${need.text[lang]}?`;
          phonetics[lang] = `${open.phonetics[lang]} ${need.phonetics[lang]}?`;
        }
      }
    } else if (ageGroup === '7-9') {
      // Age 7-9: Elementary polite conversational single sentence
      if (lang === 'ja' || lang === 'ko') {
        targetPhrases[lang] = `${need.text[lang]} ${open.text[lang]}？`;
        phonetics[lang] = `${need.phonetics[lang]} ${open.phonetics[lang]}?`;
      } else {
        targetPhrases[lang] = `${open.text[lang]} ${need.text[lang]}?`;
        phonetics[lang] = `${open.phonetics[lang]} ${need.phonetics[lang]}?`;
      }
    } else {
      // Age 10-12 & 13-16: Authentic native colloquial single sentence
      if (lang === 'ja' || lang === 'ko') {
        targetPhrases[lang] = `${need.text[lang]} ${open.text[lang]}。`;
        phonetics[lang] = `${need.phonetics[lang]} ${open.phonetics[lang]}.`;
      } else {
        targetPhrases[lang] = `${open.text[lang]} ${need.text[lang]}.`;
        phonetics[lang] = `${open.phonetics[lang]} ${need.phonetics[lang]}.`;
      }
    }
    // Translation equals target phrase for that mother tongue
    translations[lang] = targetPhrases[lang];
  }

  // Bind canonical progressive conversational engine item
  const langCodesList: LanguageCode[] = [
    'en', 'es', 'ur', 'hi', 'ar', 'fr', 'zh', 'de', 'pt', 'ru', 'ja', 'ko', 'tr', 'id', 'it'
  ];
  for (const lang of langCodesList) {
    const langCurr = getConversationalCurriculum({
      day: dayNumber,
      ageGroup,
      level,
      topicId,
      targetLanguage: lang,
      motherTongue: 'en',
      weekSeed,
      remediationVariant: weekSeed > 0 ? 'B' : 'A',
    });
    const lItem = langCurr.items[sentenceIdx - 1] || langCurr.items[0];
    targetPhrases[lang] = lItem.targetText;
    phonetics[lang] = lItem.romanized;
    translations[lang] = lItem.english.replace(/^"|"$/g, '');
  }

  return {
    id: `${topicId}-d${dayNumber}-s${sentenceIdx}`,
    speaker: sentenceIdx === 1 ? 'Learner' : sentenceIdx === 2 ? 'Companion' : 'Native Guide',
    targetPhrases,
    phonetics,
    translations,
  };
}

/**
 * Helper to get the 3 sentences for a specific topic on a specific day
 */
export function getTopicDailySentences(
  topic: TopicScenario,
  dayNumber: number,
  level: LearnerLevel,
  ageGroup: AgeGroup,
  weekSeed = 0
): DialoguePhrase[] {
  return [1, 2, 3].map((sIdx) =>
    generateDailySentences(topic.id, dayNumber, sIdx, level, ageGroup, weekSeed)
  );
}
